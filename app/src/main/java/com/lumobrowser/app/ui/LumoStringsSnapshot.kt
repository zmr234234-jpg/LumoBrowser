/**
 * All user-facing text for a screen, resolved from a language-correct [Context].
 *
 * Screens do `val s = LocalLumoStrings.current` and then read plain properties, which keeps call
 * sites short (`s.save`, `s.delete`) while leaving exactly one place that knows the resource names.
 *
 * The context is supplied by [LocalLumoStrings], which the Activity provides from the Context whose
 * `Configuration` carries the chosen language. An earlier version instead read `LocalContext.current`
 * through a lambda so this class could stay non-composable; the Compose compiler checks a composable
 * call where the lambda is *created*, so that shape could not compile from a non-composable property
 * getter, and it reported as "Unresolved reference: current" at every `LocalLumoStrings.current`.
 * Keeping the class plain and injecting a Context avoids the whole problem.
