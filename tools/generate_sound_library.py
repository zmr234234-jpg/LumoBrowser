"""Generate SoundLibrary.kt — the cue x style -> res/raw mapping.

Writing 76 resource references by hand is 76 opportunities for a typo that the compiler
would catch only if the name happened not to exist; a transposed style (press_soft listed
under Glass) would compile perfectly and ship the wrong sound. Generating the table from
the files that actually exist on disk removes both failure modes, and the generator is
re-run whenever the asset set changes.
"""
import os

# Paths are derived from this file's own location so the generator runs from any checkout,
# on any drive, on any OS. It used to carry absolute paths from the machine that wrote it,
# which made it fail with FileNotFoundError everywhere else.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

RAW = os.path.join(REPO_ROOT, "app", "src", "main", "res", "raw")
OUT = os.path.join(
    REPO_ROOT, "app", "src", "main", "java", "com", "lumobrowser", "app", "feedback",
    "SoundLibrary.kt",
)

STYLES = ["soft", "crisp", "glass", "deep"]
STYLE_ENUM = {"soft": "Soft", "crisp": "Crisp", "glass": "Glass", "deep": "Deep"}

# Enum entry name per cue stem, in the order they are declared in SoundCue.kt.
CUE_ENUM = {
    "press": "Press",
    "release": "Release",
    "click": "Click",
    "toggle": "Toggle",
    "navigate": "Navigate",
    "dialog_open": "DialogOpen",
    "dialog_close": "DialogClose",
    "bookmark_added": "BookmarkAdded",
    "settings_saved": "SettingsSaved",
    "confirm": "Confirm",
    "delete_confirm": "DeleteConfirm",
    "error": "Error",
    "load_start": "LoadStart",
    "load_success": "LoadSuccess",
    "load_failure": "LoadFailure",
    "vpn_connecting": "VpnConnecting",
    "vpn_connected": "VpnConnected",
    "vpn_failed": "VpnFailed",
    "launch_end": "LaunchEnd",
}

on_disk = {f[:-4] for f in os.listdir(RAW) if f.endswith(".wav")}

missing = []
for cue in CUE_ENUM:
    for style in STYLES:
        if "sfx_{}_{}".format(cue, style) not in on_disk:
            missing.append("sfx_{}_{}.wav".format(cue, style))
if missing:
    raise SystemExit("assets missing:\n  " + "\n  ".join(missing))

lines = []
lines.append("package com.lumobrowser.app.feedback")
lines.append("")
lines.append("import androidx.annotation.RawRes")
lines.append("import com.lumobrowser.app.R")
lines.append("import com.lumobrowser.app.data.SoundStyle")
lines.append("")
lines.append("/**")
lines.append(" * Maps a [SoundCue] and a [SoundStyle] to the generated asset for that pair.")
lines.append(" *")
lines.append(" * Generated by `tools/generate_sound_library.py` from the files actually present in")
lines.append(" * `res/raw`. Do not edit by hand: the table has one entry per cue/style pair and a")
lines.append(" * hand-edited version can silently pair a cue with the wrong style, which compiles and")
lines.append(" * sounds wrong. `SoundLibraryTest` re-derives the expected resource names from the")
lines.append(" * enums and fails if this table and the asset set ever disagree.")
lines.append(" */")
lines.append("internal object SoundLibrary {")
lines.append("")
lines.append("    /** Every cue in every style. Never returns 0: the coverage is asserted by a test. */")
lines.append("    @RawRes")
lines.append("    fun rawFor(cue: SoundCue, style: SoundStyle): Int = when (cue) {")
for cue, enum in CUE_ENUM.items():
    lines.append("        SoundCue.{} -> when (style) {{".format(enum))
    for style in STYLES:
        lines.append("            SoundStyle.{} -> R.raw.sfx_{}_{}".format(STYLE_ENUM[style], cue, style))
    lines.append("        }")
lines.append("    }")
lines.append("")
lines.append("    /** Every asset, for preloading. Order is stable so warm-up is reproducible. */")
lines.append("    val all: List<Int> = listOf(")
for cue in CUE_ENUM:
    row = ", ".join("R.raw.sfx_{}_{}".format(cue, s) for s in STYLES)
    lines.append("        " + row + ",")
lines.append("    )")
lines.append("}")
lines.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))

print("wrote", OUT)
print("cues", len(CUE_ENUM), "styles", len(STYLES), "pairs", len(CUE_ENUM) * len(STYLES))
print("res/raw wav count", len(on_disk))
